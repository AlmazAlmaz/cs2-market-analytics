TRANSLATION_PAIRS: tuple[TranslationPair, ...] = (
    COMMON_TRANSLATIONS
    + PUBLIC_TRANSLATIONS
    + DASHBOARD_TRANSLATIONS
    + COMPARISON_TRANSLATIONS
    + NOVA_TRANSLATIONS
    + DEALS_TRANSLATIONS
    + STRATEGY_TRANSLATIONS
    + DYNAMIC_TRANSLATIONS
)

# All five documents deliberately share the same catalogue.  Dynamic components
# (navigation, modal labels and cards) can move between pages without silently
# losing a translation.
PAGE_TRANSLATIONS: dict[str, tuple[TranslationPair, ...]] = {
    page_name: TRANSLATION_PAIRS for page_name in PAGE_NAMES
}


def translation_map(language: str, page_name: str | None = None) -> dict[str, str]:
    """Return an exact-text lookup map for ``language`` (``ru`` or ``en``)."""

    if language not in {"ru", "en"}:
        raise ValueError("language must be 'ru' or 'en'")
    pairs = TRANSLATION_PAIRS if page_name is None else PAGE_TRANSLATIONS[page_name]
    if language == "ru":
        return {english: russian for english, russian in pairs}
    return {russian: english for english, russian in pairs}


def pattern_templates_for(language: str) -> tuple[PatternTranslation, ...]:
    """Return source/target dynamic templates for a requested UI language."""

    if language == "ru":
        return PATTERN_TRANSLATIONS
    if language == "en":
        return tuple((russian, english) for english, russian in PATTERN_TRANSLATIONS)
    raise ValueError("language must be 'ru' or 'en'")


def validate_catalog(pairs: Iterable[TranslationPair] = TRANSLATION_PAIRS) -> None:
    """Fail fast on empty, identical or duplicate English catalogue rows.

    A few concise Russian UI labels intentionally share a translation (for
    example sentence-case and title-case English variants).  The DOM adapter
    resolves those reverse aliases deterministically, so they are not rejected
    here.
    """

    english_seen: dict[str, str] = {}
    for index, pair in enumerate(pairs):
        if not isinstance(pair, tuple) or len(pair) != 2:
            raise ValueError(f"translation row {index} is not an (en, ru) pair")
        english, russian = pair
        if not english.strip() or not russian.strip():
            raise ValueError(f"translation row {index} contains an empty value")
        if english == russian:
            raise ValueError(f"translation row {index} is identical in both languages: {english!r}")
        if english in english_seen:
            raise ValueError(f"duplicate English text: {english!r}")
        english_seen[english] = russian


def _template_fields(template: str, *, row: int, language: str) -> tuple[str, ...]:
    fields: list[str] = []
    try:
        parsed = Formatter().parse(template)
        for _literal, field_name, format_spec, conversion in parsed:
            if field_name is None:
                continue
            if not field_name.isidentifier() or format_spec or conversion:
                raise ValueError(
                    f"pattern row {row} has an unsupported {language} placeholder: "
                    f"{field_name!r}"
                )
            if field_name in fields:
                raise ValueError(
                    f"pattern row {row} repeats {language} placeholder {field_name!r}"
                )
            fields.append(field_name)
    except (ValueError, TypeError) as error:
        if str(error).startswith("pattern row"):
            raise
        raise ValueError(f"pattern row {row} has malformed {language} braces") from error
    return tuple(fields)


def validate_pattern_catalog(
    patterns: Iterable[PatternTranslation] = PATTERN_TRANSLATIONS,
) -> None:
    """Validate uniqueness and bidirectional placeholder parity for patterns."""

    english_seen: set[str] = set()
    for index, pair in enumerate(patterns):
        if not isinstance(pair, tuple) or len(pair) != 2:
            raise ValueError(f"pattern row {index} is not an (en_template, ru_template) pair")
        english, russian = pair
        if not english.strip() or not russian.strip():
            raise ValueError(f"pattern row {index} contains an empty template")
        if english == russian:
            raise ValueError(f"pattern row {index} is identical in both languages")
        if english in english_seen:
            raise ValueError(f"duplicate English pattern template: {english!r}")
        english_seen.add(english)
        english_fields = _template_fields(english, row=index, language="English")
        russian_fields = _template_fields(russian, row=index, language="Russian")
        if set(english_fields) != set(russian_fields):
            raise ValueError(
                f"pattern row {index} placeholder mismatch: "
                f"{english_fields!r} != {russian_fields!r}"
            )


validate_catalog()
validate_pattern_catalog()


